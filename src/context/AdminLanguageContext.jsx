var AdminLanguageContext = createContext()

export function AdminLanguageProvider({ children }) {
  var savedLang = 'en'
  try {
    var s = localStorage.getItem('mkv-admin-lang')
    if (s === 'en' || s === 'fr') savedLang = s
  } catch (e) {}

  var _useState = useState(savedLang)
  var language = _useState[0]
  var setLanguage = _useState[1]

  var setLang = function (lang) {
    if (lang !== 'en' && lang !== 'fr') return
    setLanguage(lang)
    try { localStorage.setItem('mkv-admin-lang', lang) } catch (e) {}
  }

  var t = function (key, params) {
    if (!params) params = {}
    var d = adminTranslations[language] || adminTranslations['en']
    var txt = d[key] || adminTranslations['en'][key] || key
    var ks = Object.keys(params)
    for (var i = 0; i < ks.length; i++) {
      txt = txt.split('{' + ks[i] + '}').join(String(params[ks[i]]))
    }
    return txt
  }

  return (
    <AdminLanguageContext.Provider value={{ language: language, setLang: setLang, t: t }}>
      {children}
    </AdminLanguageContext.Provider>
  )
}

export function useAdminLanguage() {
  var ctx = useContext(AdminLanguageContext)
  if (!ctx) throw new Error('useAdminLanguage must be used within AdminLanguageProvider')
  return ctx
}

